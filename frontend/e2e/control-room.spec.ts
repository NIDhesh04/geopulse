import {test,expect} from '@playwright/test';
test('mission controls, closures, recovery and reconnect',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:'Create run',exact:true}).click();
 await expect(page.locator('.connection')).toHaveText('Connected');
 await page.getByRole('button',{name:'Activate mission',exact:true}).click();
 await expect(page.locator('.candidate.winner')).toHaveCount(1);
 await expect(page.locator('.candidate').first()).toContainText('Live observation');
 await page.locator('.candidate').first().locator('summary').click();
 await expect(page.locator('.candidate').first()).toContainText('M1_ZERO_WAIT');
 await expect(page.locator('canvas.maplibregl-canvas')).toBeVisible();
 await expect.poll(async()=>Number(await page.locator('.map-surface').getAttribute('data-road-count'))).toBeGreaterThan(0);
 await expect(page.locator('.map-failure')).toHaveCount(0);
 const id=await page.evaluate(()=>localStorage.getItem('geopulse.run'));
 const snapshot=async()=>await (await page.request.get(`/api/runs/${id}/snapshot`)).json();
 const first=(await snapshot()).ambulance.route[0];
 await page.getByText('Scenario controls',{exact:true}).click();
 await page.getByLabel('Road segment',{exact:true}).selectOption(first);
 await page.getByRole('button',{name:'Apply road condition'}).click();
 await expect.poll(async()=>(await snapshot()).ambulance.reroutes).toBe(1);
 const alternative=(await snapshot()).ambulance.route[0];
 await page.getByLabel('Road segment',{exact:true}).selectOption(alternative);
 await page.getByRole('button',{name:'Apply road condition'}).click();
 await expect(page.locator('.stop-alert')).toContainText('all outgoing blocked');
 await page.getByLabel('Physical effect').selectOption('OPEN');
 await page.getByRole('button',{name:'Apply road condition'}).click();
 await expect(page.locator('.stop-alert')).toHaveCount(0);
 await page.getByRole('button',{name:'Step 1s'}).click();
 await expect.poll(async()=>(await snapshot()).simulationTimeSeconds).toBe(1);
 await page.getByLabel('Playback speed').selectOption('60');
 await page.getByRole('button',{name:'Play',exact:false}).click();
 await page.getByRole('button',{name:'Pause',exact:false}).click();
 const stopped=(await snapshot()).simulationTimeSeconds;
 await page.waitForTimeout(350);expect((await snapshot()).simulationTimeSeconds).toBe(stopped);
 await page.reload();await expect(page.locator('.connection')).toHaveText('Connected');
 await expect(page.locator('.event')).not.toHaveCount(0);
 await expect.poll(async()=>Number(await page.locator('.map-surface').getAttribute('data-road-count'))).toBeGreaterThan(0);
 await context.setOffline(true);await expect(page.locator('.connection')).toHaveClass(/offline/,{timeout:10000});
 await expect(page.locator('.metrics')).toContainText('Stale');
 await context.setOffline(false);await expect(page.locator('.connection')).toHaveText('Connected',{timeout:10000});
 await expect(page.locator('.map-failure')).toHaveCount(0);
 await expect.poll(async()=>Number(await page.locator('.map-surface').getAttribute('data-road-count'))).toBeGreaterThan(0);
 await page.screenshot({path:'/tmp/geopulse-control-room.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'/tmp/geopulse-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
